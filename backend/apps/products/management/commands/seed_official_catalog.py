class Command(BaseCommand):
    help = "Seed the official 90-product catalog across 18 approved categories (50 Wood Works, 15 Metal Works, 25 Hybrid Works)."

    def handle(self, *args, **options):
        self.stdout.write(self.style.NOTICE("Starting Official 90-Product Catalog Seeding..."))

        # Paths
        base_dir = settings.BASE_DIR
        media_products_dir = os.path.join(settings.MEDIA_ROOT, "products")
        media_categories_dir = os.path.join(settings.MEDIA_ROOT, "categories")
        services_dir = os.path.join(base_dir, "..", "frontend", "public", "images", "services")
        cat_covers_dir = os.path.join(base_dir, "..", "frontend", "public", "images", "categories")

        os.makedirs(media_products_dir, exist_ok=True)
        os.makedirs(media_categories_dir, exist_ok=True)

        # 1. Sync Category Cover Images
        for cat_info in APPROVED_CATEGORIES:
            cover_file = cat_info["cover_file"]
            src_cover = os.path.join(cat_covers_dir, cover_file)
            dst_cover = os.path.join(media_categories_dir, cover_file)
            if os.path.exists(src_cover) and not os.path.exists(dst_cover):
                shutil.copy2(src_cover, dst_cover)

        # 2. Seed / Update the 18 Approved Categories
        category_objects = {}
        approved_slugs = [cat["slug"] for cat in APPROVED_CATEGORIES]

        for cat_info in APPROVED_CATEGORIES:
            slug = cat_info["slug"]
            cat_obj, created = Category.objects.update_or_create(
                slug=slug,
                defaults={
                    "name": cat_info["name"],
                    "name_am": cat_info["name_am"],
                    "description": cat_info["description"],
                    "description_am": cat_info["description_am"],
                    "image": f"categories/{cat_info['cover_file']}",
                    "is_active": True,
                }
            )
            category_objects[cat_info["name"]] = cat_obj
            status_text = "Created" if created else "Updated"
            self.stdout.write(f"{status_text} category: {cat_info['name']} (slug: {slug})")

        # Deactivate any legacy unapproved categories
        unapproved_categories = Category.objects.exclude(slug__in=approved_slugs)
        unapproved_count = unapproved_categories.count()
        if unapproved_count > 0:
            self.stdout.write(f"Deactivating {unapproved_count} unapproved categories...")
            unapproved_categories.update(is_active=False)

        # 3. Associate Service Records if available
        wood_service = Service.objects.filter(slug__in=["wood-works", "woodworks"]).first()
        metal_service = Service.objects.filter(slug__in=["metal-works", "metalworks"]).first()
        hybrid_service = Service.objects.filter(slug__in=["hybrid-metal-wood", "hybrid-metal-and-wood", "hybrid"]).first()

        # 4. Deactivate legacy products outside the 90 official SKUs
        official_skus = [item["sku"] for item in CATALOG_DATA]
        legacy_products = Product.objects.exclude(sku__in=official_skus)
        legacy_count = legacy_products.count()
        if legacy_count > 0:
            self.stdout.write(f"Deactivating {legacy_count} legacy products...")
            legacy_products.update(is_active=False)

        # 5. Create or update each of the 90 official products
        created_count = 0
        updated_count = 0

        for item in CATALOG_DATA:
            sku = item["sku"]
            cat_obj = category_objects[item["category_name"]]
            if item["service_category"] == ServiceCategoryChoice.WOOD_WORKS:
                svc_record = wood_service
            elif item["service_category"] == ServiceCategoryChoice.HYBRID_METAL_WOOD:
                svc_record = hybrid_service
            else:
                svc_record = metal_service

            # Verify image file exists in media/products
            target_media_path = os.path.join(media_products_dir, item["image_file"])
            if not os.path.exists(target_media_path):
                # Copy from services_dir
                src = os.path.join(services_dir, item["image_file"])
                if os.path.exists(src):
                    shutil.copy2(src, target_media_path)
                else:
                    self.stderr.write(self.style.WARNING(f"Image not found for {sku}: {item['image_file']}"))

            dims = item["dimensions"]

            product, created = Product.objects.update_or_create(
                sku=sku,
                defaults={
                    "name": item["name"],
                    "name_am": item["name_am"],
                    "category": cat_obj,
                    "service": svc_record,
                    "product_type": item["category_name"],
                    "subcategory": item["category_name"],
                    "subcategory_am": item["category_name_am"],
                    "service_category": item["service_category"],
                    "short_description": item["description"][:280],
                    "short_description_am": item["description_am"][:280],
                    "description": item["description"],
                    "description_am": item["description_am"],
                    "detailed_description": item["description"],
                    "material": item["material"],
                    "material_am": MATERIAL_AMHARIC_MAP.get(item["material"], item["material"]),
                    "dimensions_length": Decimal(str(dims[0])),
                    "dimensions_width": Decimal(str(dims[1])),
                    "dimensions_height": Decimal(str(dims[2])),
                    "dimensions_unit": "cm",
                    "starting_price": item["price"],
                    "unit": "piece",
                    "stock_status": Product.StockStatus.MADE_TO_ORDER,
                    "is_active": True,
                    "is_featured": sku.endswith("001"),
                    "is_customizable": True,
                }
            )

            if created:
                created_count += 1
            else:
                updated_count += 1

            # Sync primary image
            product.images.all().delete()
            ProductImage.objects.create(
                product=product,
                image=f"products/{item['image_file']}",
                is_primary=True,
                caption=f"{item['name']} ({sku})"
            )

        active_count = Product.objects.filter(is_active=True).count()
        self.stdout.write(self.style.SUCCESS(
            f"Successfully seeded {len(CATALOG_DATA)} products across {len(APPROVED_CATEGORIES)} categories! "
            f"({created_count} created, {updated_count} updated). Total active products in database: {active_count}."
        ))
